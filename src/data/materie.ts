// Prove in locale: con SOLO_MATERIE="analisi-1,precorso" le altre materie risultano in preparazione (build più rapida).
// Nel Worker e nella build di Cloudflare la variabile non c'è e non cambia nulla.
const SOLO = (typeof process !== 'undefined' && process.env?.SOLO_MATERIE || '').split(',').map((s) => s.trim()).filter(Boolean);
export const MATERIE: Materia[] = ELENCO.map((m) => ({ ...m, prezzo: (PREZZI as Record<string, number>)[m.slug], ...(SOLO.length && !SOLO.includes(m.slug) ? { attiva: false } : {}) }));

export const SEZIONI = [
  { slug: 'teoria', titolo: 'Teoria' },
  { slug: 'esercizi-svolti', titolo: 'Esercizi svolti' },
  { slug: 'esercizi', titolo: 'Esercizi da fare' },
] as const;

export function materia(slug: string): Materia {
  return MATERIE.find((m) => m.slug === slug)!;
}
export function argomento(m: string, a: string): Argomento {
  return materia(m).argomenti.find((x) => x.slug === a)!;
}
// Tutte le coppie (materia, argomento) delle materie attive, per getStaticPaths.
export function coppie(sezione?: 'esercizi') {
  return MATERIE.filter((m) => m.attiva && (sezione !== 'esercizi' || m.eserciziDaFare !== false))
    .flatMap((m) => m.argomenti.map((a) => ({ materia: m.slug, argomento: a.slug })));
}
// I gruppi (percorsi di studi) nell'ordine in cui compaiono in home e nell'indice.
export function gruppi(): string[] {
  return [...new Set(MATERIE.map((m) => m.gruppo))];
}
