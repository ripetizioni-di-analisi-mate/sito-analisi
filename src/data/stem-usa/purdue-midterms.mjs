function midterm(number, coverage, items) {
  const id = 'exam-' + number;
  return {
    id,
    name: 'Exam ' + number + ' practice',
    description: coverage,
    minutes: 30,
    questions: items.map(([topic, lessons, prompt, correct, distractors, steps, review], index) => {
      const answer = (index * 3 + number) % 5;
      const choices = [...distractors];
      choices.splice(answer, 0, correct);
      return { id: id + '-' + (index + 1), topic, lessons, prompt, choices, answer, steps, review: [review] };
    }),
  };
}

